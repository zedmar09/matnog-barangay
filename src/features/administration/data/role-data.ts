const access = (entries: Record<string, PermissionLevel>, sensitive: string[] = []): ModulePermission[] =>
  MODULES.map((module) => ({
    ...module,
    level: entries[module.moduleId] ?? "No access",
    sensitiveFields: sensitive.includes(module.moduleId),
  }));

const role = (
  id: string,
  name: RoleName,
  description: string,
  scope: RoleDefinition["scope"],
  type: RoleDefinition["type"],
  entries: Record<string, PermissionLevel>,
  sensitive: string[] = [],
): RoleDefinition => ({
  id,
  name,
  description,
  scope,
  type,
  permissions: access(entries, sensitive),
  lastUpdated: "2026-09-18",
  updatedBy: "Amelia Fortes",
});

